import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export async function prepareRelease({projectRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), outDir=path.join(projectRoot, 'dist')}={}) {
  const readJson=async name=>JSON.parse(await fs.readFile(path.join(projectRoot, name), 'utf8'));
  const [manifest, metadata, lock, versions]=await Promise.all(['manifest.json', 'package.json', 'package-lock.json', 'versions.json'].map(readJson));
  const version=manifest.version;
  if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)||manifest.id!=='ctz-today-sidebar'||metadata.version!==version||lock.version!==version||lock.packages[''].version!==version||versions[version]!==manifest.minAppVersion)throw Error('Release metadata mismatch');
  const changelog=await fs.readFile(path.join(projectRoot, 'CHANGELOG.md'), 'utf8');
  const heading=`## ${version} — `;
  const start=changelog.indexOf(heading);
  if(start<0)throw Error('Missing versioned changelog entry');
  const entry=changelog.slice(start).split(/\n## /)[0].trim();
  const files=['main.js', 'manifest.json', 'styles.css', 'LICENSE'];
  // Read everything before writing; never reuse or overwrite frozen assets.
  const assets=await Promise.all([...files.map(name=>path.join(projectRoot, name)), path.join(projectRoot, 'dist/ctz-today-sidebar.zip')].map(file=>fs.readFile(file)));
  if(assets.some(data=>!data.length))throw Error('Empty release asset');
  await fs.mkdir(outDir, {recursive:true});
  const frozen=path.join(outDir, 'release');
  await fs.mkdir(frozen);
  for(const [i,name] of [...files, 'ctz-today-sidebar.zip'].entries())await fs.writeFile(path.join(frozen, name), assets[i], {flag:'wx'});
  const notes=`${entry}\n\nRequires Obsidian ${manifest.minAppVersion} or later. Download ctz-today-sidebar.zip and update the plugin manually, preserving your existing data.json.\n\nAll automated tests passed. All five release assets have GitHub artifact attestations generated by the release workflow. Uploaded assets are downloaded again and verified before publication.\n`;
  await fs.writeFile(path.join(outDir, 'release-notes.md'), notes, {flag:'wx'});
  return {version, frozen};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(await prepareRelease());
